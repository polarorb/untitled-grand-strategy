//! Static game data: scenario definitions, country/province data, and the
//! RON loaders for them. This crate knows nothing about ECS or rendering.
//!
//! All gameplay content lives in `assets/data/` as RON files and is validated
//! at load time. Ids are newtyped so a ProvinceId can never be confused with
//! a CountryId at compile time.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;

#[derive(Debug, thiserror::Error)]
pub enum DataError {
    #[error("io error reading {path}: {source}")]
    Io {
        path: String,
        source: std::io::Error,
    },
    #[error("parse error in {path}: {source}")]
    Parse {
        path: String,
        source: ron::error::SpannedError,
    },
    #[error("validation error: {0}")]
    Validation(String),
}

/// Three-letter tag, e.g. "USA", "SOV", "PRC". Ordered so that iteration over
/// keyed maps is deterministic.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct CountryTag(pub String);

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct ProvinceId(pub u32);

/// Economic region (grid zone / logistics cluster). Generated by mapgen;
/// never crosses a country border.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, Default,
)]
pub struct RegionId(pub u16);

/// Extractable resource kinds with map locality (diffuse goods like grain
/// and manufactured goods are computed, not deposited).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum DepositKind {
    Coal,
    Oil,
    Iron,
    Uranium,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RegionDef {
    pub id: RegionId,
    /// Named after its most populous province.
    pub name: String,
}

/// The two poles of the Cold War plus the space in between.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Alignment {
    WesternBloc,
    EasternBloc,
    NonAligned,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CountryDef {
    pub tag: CountryTag,
    pub name: String,
    pub alignment: Alignment,
    /// National map color, sRGB. Distinct per country (political map mode).
    pub color: (u8, u8, u8),
    pub capital: ProvinceId,
    /// 0-100. How firmly the government controls the country.
    pub stability: u8,
    /// Starting industrial capacity (abstract units).
    pub industry: u32,
    /// Whether this country has nuclear weapons at scenario start.
    pub nuclear_power: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ProvinceDef {
    pub id: ProvinceId,
    pub name: String,
    pub owner: CountryTag,
    pub terrain: Terrain,
    /// (longitude, latitude) of the province center in degrees. Placeholder
    /// geometry until real polygons arrive via the mapgen tool.
    pub center: (f32, f32),
    /// Population in thousands.
    pub population_k: u32,
    /// Urban population in thousands (subset of population_k).
    #[serde(default)]
    pub urban_k: u32,
    /// Economic region this province belongs to.
    #[serde(default)]
    pub region: RegionId,
    /// Resource deposits (kind, abstract size 1-10).
    #[serde(default)]
    pub deposits: Vec<(DepositKind, u32)>,
    pub adjacent: Vec<ProvinceId>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Terrain {
    Plains,
    Forest,
    Hills,
    Mountain,
    Desert,
    Jungle,
    Urban,
    Marsh,
    Tundra,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ScenarioDef {
    pub name: String,
    /// Start date as (year, month, day).
    pub start_date: (i32, u8, u8),
    pub description: String,
}

/// Presentation metadata for the nation-select screen. Researched per
/// nation as of the scenario start date; flag/portrait images live at
/// `assets/flags/<TAG>.png` and `assets/leaders/<TAG>.png`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NationMeta {
    pub tag: CountryTag,
    /// Proper period name, e.g. "Kingdom of Egypt".
    pub display_name: String,
    /// De-facto ruler at scenario start (not ceremonial figurehead).
    pub leader_name: String,
    pub leader_title: String,
    pub government: String,
    /// Two paragraphs of historic-situation text, second person.
    pub situation: String,
    /// Featured in the "interesting picks" quick selector.
    pub interesting: bool,
    /// One-line pitch for playing this nation.
    pub hook: String,
}

/// The three bloc-band names as they appear in event data.
pub const ALIGNMENT_NAMES: [&str; 3] = ["WesternBloc", "EasternBloc", "NonAligned"];

/// A scripted historical event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EventDef {
    pub id: String,
    pub trigger: EventTrigger,
    /// Daily chance to fire once the trigger condition holds (permille);
    /// absent = fires immediately when the condition holds.
    #[serde(default)]
    pub chance_permille: Option<u32>,
    pub title: String,
    /// Teletype-voice body text shown to the player.
    pub body: String,
    /// The country whose decision this is. None = world event
    /// (effects/options[0] apply immediately on firing).
    #[serde(default)]
    pub country: Option<CountryTag>,
    /// Days the deciding country has before option 0 auto-applies.
    #[serde(default)]
    pub deadline_days: u8,
    /// Choice options; the first is the default/historical choice.
    /// Events without options use `effects` directly.
    #[serde(default)]
    pub options: Vec<EventOption>,
    #[serde(default)]
    pub effects: Vec<EventEffect>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EventOption {
    pub label: String,
    pub effects: Vec<EventEffect>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum EventTrigger {
    /// Fires at (year, month, day, hour).
    Date((i32, u8, u8, u8)),
    /// Fires N days after a war begins between the two countries.
    WarDaysElapsed {
        a: CountryTag,
        b: CountryTag,
        days: u16,
    },
    /// Fires when at least `count` of `owner`'s 1950 provinces are held
    /// by countries at war with `owner`.
    ProvincesLost {
        owner: CountryTag,
        count: u16,
    },
    /// Fires when global tension (internal tenths, displayed x10) is
    /// at or above / below the threshold.
    TensionAbove {
        tenths: i32,
    },
    TensionBelow {
        tenths: i32,
    },
    /// Chain: fires `days_after` days after the named event fired.
    EventFired {
        id: String,
        days_after: u16,
    },
    /// Chain: fires `days_after` days after the named event was
    /// resolved with the given option index.
    OptionChosen {
        id: String,
        option: u8,
        days_after: u16,
    },
    /// Fires while the country's current bloc band is the named one:
    /// "WesternBloc" | "EasternBloc" | "NonAligned" (influence.md).
    /// Lets chains branch on who won a contest.
    AlignmentBand {
        country: CountryTag,
        band: String,
    },
    /// Fires while the country's dynamic stability is below `value`.
    StabilityBelow {
        country: CountryTag,
        value: u8,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum EventEffect {
    AdjustTension(i32),
    DeclareWar {
        a: CountryTag,
        b: CountryTag,
    },
    /// Set a country's posture toward an enemy: "Advance" or "Hold".
    SetPosture {
        country: CountryTag,
        enemy: CountryTag,
        posture: String,
    },
    /// Transfer named provinces between owners (e.g. Hainan falls).
    TransferProvinces {
        from: CountryTag,
        to: CountryTag,
        names: Vec<String>,
    },
    /// Spawn formations (intervention forces). Province resolved by
    /// (owner_1950, name).
    SpawnForces {
        owner: CountryTag,
        province_owner: CountryTag,
        province: String,
        archetype: String,
        divisions: u32,
        quality: u32,
    },
    /// Patron military aid: add points to a country's military stockpile
    /// (the upkeep/raising currency). How PRK survives its own economy.
    GrantStock {
        country: CountryTag,
        amount: u64,
    },
    /// Declare a war aim: "StatusQuoAnte" | "Punish" | "NewLine" | "Unify".
    SetWarAim {
        country: CountryTag,
        enemy: CountryTag,
        aim: String,
    },
    /// International standing (UN mandates, coalition breadth).
    GrantLegitimacy {
        country: CountryTag,
        amount: i32,
    },
    /// Realign a country's bloc: "WesternBloc" | "EasternBloc" |
    /// "NonAligned". Flips basing, patronage, allocator behavior.
    SetAlignment {
        country: CountryTag,
        alignment: String,
    },
    /// Coups, uprisings, and steadied governments (clamped 0-100).
    AdjustStability {
        country: CountryTag,
        delta: i32,
    },
    /// Aid or war damage: centi-points of industry, distributed across
    /// the recipient's regions proportionally.
    GrantIndustry {
        country: CountryTag,
        centi: i64,
    },
    /// A new state is born: EXACTLY the listed provinces (by name
    /// and/or stable id, owned by `from` in 1950) transfer to
    /// `country`; region ownership follows the majority holder;
    /// manpower seeds from the transferred population. Ids are the
    /// robust binding (generic colonial names are often ambiguous);
    /// tools/timeline/integrate.py generates them from Natural Earth
    /// attribution.
    Independence {
        country: CountryTag,
        from: CountryTag,
        #[serde(default)]
        provinces: Vec<String>,
        #[serde(default)]
        province_ids: Vec<u32>,
    },
    /// Authorize the thermonuclear ("Super") follow-on program.
    AuthorizeThermonuclear {
        country: CountryTag,
    },
    /// Persistent nuclear-program speed modifier (espionage boosts,
    /// political acceleration). Permille, multiplicative with others.
    AdjustProgramSpeed {
        country: CountryTag,
        permille: u32,
    },
    /// Found a nuclear program (AI decisions, scripted starts).
    FoundNuclearProgram {
        country: CountryTag,
        route: String,
    },
    /// Influence: move a country's position (and baseline — a scripted
    /// shift is structural) by `delta` on the -1000 East..+1000 West
    /// axis (influence.md).
    ShiftAlignment {
        country: CountryTag,
        delta: i16,
    },
    /// Influence: lock the current band for `months` (0 = unlock) under
    /// a label ("WARSAW PACT", "STATE TREATY"). Locked positions do not
    /// move by program; breaking a lock is an explicit act.
    LockAlignment {
        country: CountryTag,
        months: u16,
        label: String,
    },
    /// Influence: a patron crushes a rising — re-locks the satellite
    /// for five years toward the patron, records the crush (the next
    /// rising is worse), and hardens the position to the patron's edge.
    Crush {
        patron: CountryTag,
        country: CountryTag,
    },
    /// Influence: who equips and trains the army — "West" | "East" |
    /// "None". The coup gate.
    SetArmyPatron {
        country: CountryTag,
        patron: String,
    },
    /// Influence: a dated unlock — one more standing-program slot (or,
    /// with `ops: true`, one more active-operation slot).
    GrantInfluenceSlot {
        country: CountryTag,
        #[serde(default)]
        ops: bool,
    },
    /// Influence: the sponsor may now run PRESENCE programs (Campaign
    /// of Truth, Radio Free Europe).
    UnlockPresence {
        country: CountryTag,
    },
    /// Influence: open a contested window on a country for `months`
    /// (rates doubled, hysteresis suspended). Independence does this
    /// automatically for 24 months.
    OpenContest {
        country: CountryTag,
        months: u16,
    },
}

/// Static influence-pillar content (influence.ron; optional). Every
/// row is sourced in the file's comments (historian pass, 2026-09-02).
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct InfluenceData {
    /// Per-country 1950 seed (or, for states born later, the seed at
    /// birth). Tags absent here seed from CountryDef.alignment.
    #[serde(default)]
    pub seeds: Vec<InfluenceSeedDef>,
    /// The contested set the standings score over.
    #[serde(default)]
    pub battlegrounds: Vec<BattlegroundDef>,
    /// Per-region Presence / Domination / Control counts.
    #[serde(default)]
    pub thresholds: Vec<RegionThresholdDef>,
    /// Sourced election calendar for the battleground democracies.
    #[serde(default)]
    pub elections: Vec<ElectionDef>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InfluenceSeedDef {
    pub tag: CountryTag,
    /// -1000 East .. +1000 West.
    pub position: i16,
    /// A standing lock: label and the year it lapses (None = open-ended).
    #[serde(default)]
    pub lock: Option<LockDef>,
    /// "West" | "East" | absent.
    #[serde(default)]
    pub army_patron: Option<String>,
    /// Competitive elections exist (false: one-party, military,
    /// absolute monarchy, colonial).
    #[serde(default = "default_true")]
    pub open: bool,
    /// Sourced stability, overriding CountryDef's flat value at seed.
    #[serde(default)]
    pub stability: Option<u8>,
    /// Standing-program slots and active-operation slots this country
    /// starts with (superpowers 3/1, UK and France 2/1, most 0/0).
    #[serde(default)]
    pub slots: u8,
    #[serde(default)]
    pub op_slots: u8,
    /// For states born by Independence: the date the independence date
    /// was publicly announced (programs may target the tag from then).
    #[serde(default)]
    pub announced: Option<(i32, u8, u8)>,
}

fn default_true() -> bool {
    true
}

